#include <string>

namespace {

// `sipi::test::data_dir()` honours Bazel's SIPI_TEST_DATA_DIR env and falls
// back to the historical CMake build-tree relative path when unset. See
// test/test_paths.h.
static const std::string kMalformedRoot = sipi::test::data_dir() + "/images/malformed";
static const std::string kXmpTruncated = kMalformedRoot + "/jpeg_xmp_truncated.jpg";
static const std::string kIccShortApp2 = kMalformedRoot + "/jpeg_icc_short_app2.jpg";
static const std::string kIccNoDescription = kMalformedRoot + "/jpeg_icc_no_description.jpg";
static const std::string kPhotoshopShortApp13 = kMalformedRoot + "/jpeg_photoshop_short_app13.jpg";
static const std::string kPhotoshopOvershootApp13 = kMalformedRoot + "/jpeg_photoshop_overshoot_app13.jpg";
static const std::string kExifTruncated = kMalformedRoot + "/jpeg_exif_truncated.jpg";

}// namespace

// -------------------------------------------------------------------------
// DEV-6066 — read_shape() XMP marker walk
// -------------------------------------------------------------------------

TEST(JpegMarkerRegression, XmpTruncatedReadShapeDoesNotCrash)
{
  Sipi::SipiIOJpeg io;
  Sipi::Result<Sipi::SipiImgInfo> result{ Sipi::SipiImgInfo{} };
  // The bounded extraction must not walk past marker->data_length; the
  // underlying JPEG image data is well-formed, so the shape probe still
  // succeeds once the XMP segment is safely skipped.
  ASSERT_NO_THROW(result = io.read_shape(kXmpTruncated));
  ASSERT_TRUE(result.has_value());
  const auto &info = *result;
  EXPECT_EQ(info.success, Sipi::SipiImgInfo::DIMS);
  EXPECT_GT(info.width, 0);
  EXPECT_GT(info.height, 0);
}

TEST(JpegMarkerRegression, XmpTruncatedFullReadDoesNotCrash)
{
  Sipi::SipiImage img;
  EXPECT_TRUE(img.read(kXmpTruncated).has_value());
}

// -------------------------------------------------------------------------
// N1 — read() ICC (APP2) length underflow
// -------------------------------------------------------------------------
//
// read_shape() does not process APP2/ICC markers at all (only JPEG_COM,
// APP1 EXIF/XMP, and APP13 Photoshop) — the ICC underflow guard only
// applies to the full read() path, so this fixture is exercised there.

TEST(JpegMarkerRegression, IccShortApp2ReadDoesNotCrash)
{
  Sipi::SipiImage img;
  EXPECT_TRUE(img.read(kIccShortApp2).has_value());
}

// -------------------------------------------------------------------------
// DEV-7078 — Icc::parse() classification of a description-less profile
// -------------------------------------------------------------------------
//
// Unlike jpeg_icc_short_app2.jpg (which pins the N1 bounds guard and never
// reaches Icc::parse()), this fixture carries a well-formed APP2 ICC
// segment whose profile has a valid header but zero tags — no description
// tag — so the embedded bytes do reach Icc::parse(), and the read must both
// succeed and classify the profile as icc_unknown.

TEST(JpegMarkerRegression, IccNoDescriptionClassifiesAsUnknown)
{
  Sipi::SipiImage img;
  auto result = img.read(kIccNoDescription);
  ASSERT_TRUE(result.has_value());
  const auto icc = img.getIcc();
  ASSERT_NE(icc, nullptr);
  EXPECT_EQ(icc->getProfileType(), Sipi::icc_unknown);
}

