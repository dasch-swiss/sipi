// -------------------------------------------------------------------------
// parse_photoshop() even-padding pointer overshoot (adversarial review)
// -------------------------------------------------------------------------
//
// A *valid* "Photoshop 3.0\0" identifier (so the caller's data_length + strncmp
// guard passes and parse_photoshop() actually runs) followed by exactly one
// 7-byte 8BIM resource with an empty (even-length) Pascal name and nothing
// after it. The name-length byte plus the odd->even padding bump pushed `ptr`
// one byte past `end`; the next bounds check then computed `end - ptr == -1`,
// cast to SIZE_MAX, and over-read past the marker's heap buffer. Under ASan
// (CI) the pre-fix over-read aborts here; locally the fixture still decodes
// because the crafted resource is skipped once the padded-length guard breaks.

TEST(JpegMarkerRegression, PhotoshopOvershootApp13ReadShapeDoesNotCrash)
{
  Sipi::SipiIOJpeg io;
  Sipi::Result<Sipi::SipiImgInfo> result{ Sipi::SipiImgInfo{} };
  ASSERT_NO_THROW(result = io.read_shape(kPhotoshopOvershootApp13));
  ASSERT_TRUE(result.has_value());
  const auto &info = *result;
  EXPECT_EQ(info.success, Sipi::SipiImgInfo::DIMS);
  EXPECT_GT(info.width, 0);
  EXPECT_GT(info.height, 0);
}

TEST(JpegMarkerRegression, PhotoshopOvershootApp13FullReadDoesNotCrash)
{
  Sipi::SipiImage img;
  EXPECT_TRUE(img.read(kPhotoshopOvershootApp13).has_value());
}

// -------------------------------------------------------------------------
// DEV-7056 — Exif::parse() failure is fatal (not a bounds guard)
// -------------------------------------------------------------------------
//
// The APP1 payload is `Exif\0\0` followed by a truncated little-endian TIFF
// header ("II*", 3 bytes: no magic-number low byte, no IFD offset, no IFD).
// It is long enough to clear every length check upstream of the parser, so
// `read()` actually calls `Exif::parse()`, which calls
// `Exiv2::ExifParser::decode()`; that throws on the malformed TIFF structure
// and `read()` reports the failure as `kMetadataParseFailed` rather than
// admitting the file with corrupt embedded metadata.

TEST(JpegMarkerRegression, ExifTruncatedFullReadFailsWithMetadataParseFailed)
{
  Sipi::SipiImage img;
  auto result = img.read(kExifTruncated);
  ASSERT_FALSE(result.has_value());
  EXPECT_EQ(result.error().code(), Sipi::ErrorCode::kMetadataParseFailed);
}
